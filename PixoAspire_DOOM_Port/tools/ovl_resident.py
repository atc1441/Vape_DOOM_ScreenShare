"""Link inputs of firmware overlays that share objects with the resident image.

usage: ovl_resident.py script --map MAIN.map --script port/ovl/ovl.ld -o OUT.ld OBJ...
       ovl_resident.py exports -o EXPORTS.ld --ovl "OBJ..." [--ovl "OBJ..."]...

An overlay of the DOOM firmware (mk/fw.mk) may be linked from objects that the resident image
links too: it is meant to hold only what the resident image dropped (unreferenced cold code,
the functions the resident link wraps).

script   Every allocated input section of OBJ that MAIN.map (the map of the resident link)
         shows gets an output section of its own at that address, NOLOAD and named .res_N:
         the overlay's references to those functions and data, static ones included, resolve
         to the resident copies, and only the other sections of OBJ end up in the blob of
         port/ovl/ovl.ld. Merged constants (strings) have no address of their own in the
         resident image, the overlay keeps a copy of the ones it uses.
         tools/pack_overlays.py accepts the .res_N sections of an overlay when they are NOBITS
         and outside the frame region.
exports  EXTERN() roots for the resident link: what the code and data reachable from each
         overlay's entry table (its .ovl_entries section) refers to outside the overlay's
         objects, and the global data of those objects it reaches, which must stay resident
         because overlays have no data of their own. Reachable follows the relocations of
         each input section, as ld.lld --gc-sections does.
"""
import argparse
import os
import re
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.dont_write_bytecode = True
import pack_overlays as po  # noqa: E402

LINE_OUT = re.compile(r"^\s*([0-9a-f]+)\s+([0-9a-f]+)\s+([0-9a-f]+)\s+\d+ (\.\S+)\s*$")
LINE_IN = re.compile(r"^\s*([0-9a-f]+)\s+([0-9a-f]+)\s+([0-9a-f]+)\s+\d+\s{9}(.*):\((\S+)\)\s*$")


def placed(path, objs):
    """(address, object, section) of every input section of objs in the map, by address."""
    out = []
    with open(path) as f:
        sec = None
        for line in f:
            m = LINE_OUT.match(line)
            if m:
                sec = m.group(4)
                continue
            m = LINE_IN.match(line)
            if not m or sec is None or not int(m.group(3), 16):
                continue
            obj, name = m.group(4), m.group(5)
            if obj in objs and not sec.startswith((".debug", ".comment", ".ARM")):
                out.append((int(m.group(1), 16), obj, name))
    return sorted(out)


def write(path, lines):
    with open(path + ".tmp", "w") as f:
        f.write("\n".join(lines) + "\n")
    os.replace(path + ".tmp", path)


def script(a):
    lines = [f"/* Generated by tools/ovl_resident.py from {a.map}: the input sections that the",
             "   resident image has, at their addresses there */", "SECTIONS", "{"]
    for k, (addr, obj, name) in enumerate(placed(a.map, set(a.objs))):
        lines.append(f"    .res_{k} {addr:#x} (NOLOAD) : {{ {obj}({name}) }}")
    write(a.out, lines + ["}", f"INCLUDE {a.script}"])


def reachable_roots(objs):
    """Undefined names and global data the sections reachable from .ovl_entries refer to."""
    elfs = [po.Elf(o) for o in objs]
    defined, data = {}, {}
    for i, e in enumerate(elfs):
        for sym in e.symbols:
            if sym["bind"] and sym["name"] and sym["shndx"] not in (po.SHN_UNDEF, po.SHN_ABS):
                defined.setdefault(sym["name"], (i, sym["shndx"]))
                if not e.sections[sym["shndx"]]["flags"] & po.SHF_EXECINSTR:
                    data.setdefault((i, sym["shndx"]), set()).add(sym["name"])
    refs = []
    for e in elfs:
        r = {}
        for s in e.sections:
            if s["type"] == po.SHT_REL and e.sections[s["info"]]["flags"] & po.SHF_ALLOC:
                tgt = r.setdefault(s["info"], [])
                for k in range(s["size"] // 8):
                    _, info = struct.unpack_from("<II", e.data, s["off"] + 8 * k)
                    tgt.append(e.symbols[info >> 8])
        refs.append(r)
    todo = [(i, k) for i, e in enumerate(elfs) for k, s in enumerate(e.sections)
            if s["name"] == ".ovl_entries"]
    seen, roots = set(todo), set()
    while todo:
        i, k = todo.pop()
        for sym in refs[i].get(k, ()):
            if sym["shndx"] == po.SHN_ABS:
                continue
            if sym["shndx"] != po.SHN_UNDEF:
                t = (i, sym["shndx"])
            elif sym["name"] in defined:
                t = defined[sym["name"]]
            else:
                roots.add(sym["name"])
                continue
            # the global names of a data section reached, merged globals included
            roots |= data.get(t, set())
            if t not in seen:
                seen.add(t)
                todo.append(t)
    return roots


def exports(a):
    roots = set()
    for group in a.ovl:
        roots |= reachable_roots(group.split())
    write(a.out, ["/* Resident symbols used by the overlays (generated) */", "EXTERN("]
          + sorted(roots) + [")"])


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("script")
    s.add_argument("--map", required=True)
    s.add_argument("--script", required=True)
    s.add_argument("-o", "--out", required=True)
    s.add_argument("objs", nargs="+")
    e = sub.add_parser("exports")
    e.add_argument("-o", "--out", required=True)
    e.add_argument("--ovl", action="append", required=True)
    a = ap.parse_args()
    script(a) if a.cmd == "script" else exports(a)
    return 0


if __name__ == "__main__":
    sys.exit(main())
