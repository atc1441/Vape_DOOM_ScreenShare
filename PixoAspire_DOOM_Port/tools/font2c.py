"""Generates platform/font8x8.c from dhepper/font8x8 (public domain).

Takes font8x8_basic.h from --src (or env FONT8X8_BASIC), or downloads it at the pinned
commit into dl/ and checks its SHA-256. Keeps U+0020..U+007E and reverses the bits of every
row, because the source stores the leftmost pixel in bit 0 and platform/text.c reads bit 7.
"""

import argparse
import hashlib
import os
import re
import sys
import urllib.request

COMMIT = "8e279d2d864e79128e96188a6b9526cfa3fbfef9"
URL = f"https://raw.githubusercontent.com/dhepper/font8x8/{COMMIT}/font8x8_basic.h"
SHA256 = "49d8df366296b203ca3211bc0672cf2a762135bf12710735b6292756b19dffd5"
ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))


def fetch(path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with urllib.request.urlopen(URL, timeout=60) as r:
        data = r.read()
    with open(path + ".part", "wb") as f:
        f.write(data)
    os.replace(path + ".part", path)


def load(src):
    with open(src, "rb") as f:
        data = f.read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SHA256:
        sys.exit(f"{src}: SHA-256 {digest} does not match the pinned {SHA256}")
    return data.decode("ascii")


def parse(text):
    rows = re.findall(r"\{\s*((?:0x[0-9A-Fa-f]{2}\s*,\s*){7}0x[0-9A-Fa-f]{2})\s*\}\s*,\s*//\s*U\+([0-9A-F]{4})", text)
    glyphs = {int(cp, 16): [int(v, 16) for v in body.split(",")] for body, cp in rows}
    missing = [cp for cp in range(0x20, 0x7F) if cp not in glyphs]
    if missing:
        sys.exit(f"glyphs missing from the source: {missing}")
    return glyphs


def rev8(v):
    return int(f"{v:08b}"[::-1], 2)


def render(glyphs):
    out = [
        "// SPDX-License-Identifier: GPL-2.0-or-later",
        "// Copyright (C) 2026 Artur Bieniek",
        "//",
        "// 8x8 font for ASCII 32..126, one byte per row, bit 7 is the leftmost pixel.",
        "// Generated by tools/font2c.py from font8x8_basic.h of https://github.com/dhepper/font8x8",
        f"// at commit {COMMIT}, with the bits of every row reversed.",
        "// The glyphs are public domain: Daniel Hepper, based on Marcel Sondaar's font8_8.asm and",
        "// the public domain IBM VGA fonts.",
        "",
        "#include <stdint.h>",
        "",
        "const uint8_t font8x8[95][8] = {",
    ]
    for cp in range(0x20, 0x7F):
        row = ", ".join(f"0x{rev8(v):02X}" for v in glyphs[cp])
        ch = chr(cp)
        label = "'\\\\'" if ch == "\\" else ("\"'\"" if ch == "'" else f"'{ch}'")
        out.append(f"    {{{row}}},  // {label}")
    out += ["};", ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--src", default=os.environ.get("FONT8X8_BASIC"),
                    help="local font8x8_basic.h (default: download into dl/)")
    ap.add_argument("--out", default=os.path.join(ROOT, "platform", "font8x8.c"))
    args = ap.parse_args()
    src = args.src
    if not src:
        src = os.path.join(ROOT, "dl", "font8x8", COMMIT[:12], "font8x8_basic.h")
        if not os.path.exists(src):
            fetch(src)
    text = render(parse(load(src)))
    with open(args.out, "w") as f:
        f.write(text)
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
