"""Build and run the host dumper against the pinned, unmodified upstream sources.

The dumper prints the upstream tables as JSON. Enum names come from the
dumper's debug info, so no C source is parsed here.
"""

import concurrent.futures
import json
import os
import re
import subprocess

from . import format as F
from .util import BUILD, UPSTREAM, ConvError, mkdirs, tmp_name, write_if_changed

CC = os.environ.get("HOSTCC", "clang")
NM = os.environ.get("NM", "llvm-nm")
DWARFDUMP = os.environ.get("DWARFDUMP", "llvm-dwarfdump")
DUMPER_SRC = os.path.join(os.path.dirname(os.path.abspath(__file__)), "dumper")
OUT = os.path.join(BUILD, "conv", "dumper")

ENGINE = ("dummy am_map doomdef doomstat dstrings d_event d_items d_iwad d_loop d_main d_mode d_net "
          "f_finale f_wipe g_game hu_lib hu_stuff info i_cdmus i_endoom i_joystick i_scale i_sound "
          "i_system i_timer memio m_argv m_bbox m_cheat m_config m_controls m_fixed m_menu m_misc "
          "m_random p_ceilng p_doors p_enemy p_floor p_inter p_lights p_map p_maputl p_mobj p_plats "
          "p_pspr p_saveg p_setup p_sight p_switch p_telept p_tick p_user r_bsp r_data r_draw "
          "r_main r_plane r_segs r_sky r_things sha1 sounds statdump st_lib st_stuff s_sound tables "
          "v_video wi_stuff w_checksum w_file w_main w_wad z_zone w_file_stdc i_input i_video "
          "doomgeneric").split()
CFLAGS = ["-O1", "-w", "-std=gnu11", "-fwrapv", "-fsigned-char", "-DNORMALUNIX", "-DLINUX",
          "-D_DEFAULT_SOURCE", "-I", UPSTREAM]
STRINGS_FROM_ENDMSG = set(F.QUITMSG_IDS)


def _run(cmd, **kw):
    r = subprocess.run(cmd, capture_output=True, text=True, **kw)
    if r.returncode:
        raise ConvError("command failed: %s\n%s%s" % (" ".join(cmd), r.stdout, r.stderr))
    return r.stdout


def _deps(dep):
    """Prerequisites listed in a compiler .d file."""
    with open(dep) as f:
        text = f.read().replace("\\\n", " ")
    return text.partition(": ")[2].split()


def _stale(out, inputs):
    if not os.path.exists(out):
        return True
    t = os.path.getmtime(out)
    return any(not os.path.exists(p) or os.path.getmtime(p) > t for p in inputs)


def _compile(job, force):
    """Compile when forced, when the object is missing or older than its source or headers."""
    cmd, src, obj = job
    dep = obj[:-2] + ".d"
    try:
        stale = force or _stale(obj, [src] + _deps(dep))
    except OSError:
        stale = True
    if stale:
        tmp, dtmp = tmp_name(obj), tmp_name(dep)
        _run(cmd + ["-MMD", "-MT", obj, "-MF", dtmp, "-c", src, "-o", tmp])
        os.replace(dtmp, dep)
        os.replace(tmp, obj)
    return obj


def _compile_all(jobs, objdir):
    """Compile jobs [(src, obj, extra flags)]. A compiler or command change rebuilds the object."""
    version = _run([CC, "--version"])
    cmds = {obj: [CC] + CFLAGS + list(extra) for src, obj, extra in jobs}
    state = os.path.join(objdir, "commands.json")
    try:
        with open(state) as f:
            old = json.load(f)
    except (OSError, ValueError):
        old = {}
    force_all = old.get("version") != version
    work = [((cmds[obj], src, obj), force_all or old.get("cmds", {}).get(os.path.basename(obj)) != cmds[obj])
            for src, obj, _ in jobs]
    with concurrent.futures.ThreadPoolExecutor(os.cpu_count() or 4) as ex:
        objs = list(ex.map(lambda w: _compile(*w), work))
    old.setdefault("cmds", {}).update({os.path.basename(o): c for o, c in cmds.items()})
    old["version"] = version
    write_if_changed(state, json.dumps(old, indent=0, sort_keys=True))
    return objs


def build():
    """Build the dumper. Returns the path of the executable."""
    if not os.path.isdir(UPSTREAM):
        raise ConvError("upstream sources missing at %s" % UPSTREAM)
    objdir = os.path.join(OUT, "obj")
    mkdirs(objdir)
    jobs = [(os.path.join(UPSTREAM, n + ".c"), os.path.join(objdir, n + ".o"), ()) for n in ENGINE]
    jobs.append((os.path.join(DUMPER_SRC, "dump_spec.c"), os.path.join(objdir, "dump_spec.o"), ()))
    jobs.append((os.path.join(DUMPER_SRC, "dump_info.c"), os.path.join(objdir, "dump_info.o"), ("-g",)))
    objs = _compile_all(jobs, objdir)
    # Action functions referenced by the state table, from the undefined symbols of info.o.
    syms = sorted(set(re.findall(r"\b(A_\w+)", _run([NM, "-u", os.path.join(objdir, "info.o")]))))
    act = ["// Generated by tools/conv/upstream.py", "#include <stddef.h>",
           "struct dmc_named_ptr { const char *name; const void *ptr; };"]
    act += ["extern void %s();" % s for s in syms]
    act.append("const struct dmc_named_ptr dmc_action_names[] = {")
    act += ["    {\"%s\", (const void *)%s}," % (s, s) for s in syms]
    act += ["    {NULL, NULL}", "};", ""]
    act_c = os.path.join(OUT, "actions.c")
    write_if_changed(act_c, "\n".join(act))
    strs = ["// Generated by tools/conv/upstream.py", "#include <stddef.h>", "#include \"d_englsh.h\"",
            "struct dmc_named_ptr { const char *name; const void *ptr; };",
            "const struct dmc_named_ptr dmc_string_values[] = {"]
    strs += ["    {\"%s\", %s}," % (s, s) for s in F.STRING_IDS if s not in STRINGS_FROM_ENDMSG]
    strs += ["    {NULL, NULL}", "};", ""]
    str_c = os.path.join(OUT, "strings.c")
    write_if_changed(str_c, "\n".join(strs))
    objs += _compile_all([(act_c, os.path.join(objdir, "actions.o"), ()),
                          (str_c, os.path.join(objdir, "strings.o"), ())], objdir)
    exe = os.path.join(OUT, "dump_info")
    if _stale(exe, objs):
        tmp = tmp_name(exe)
        _run([CC, "-o", tmp] + objs + ["-lm"])
        os.replace(tmp, exe)
    return exe


def _dwarf_enums(obj):
    """{typedef name: [(enumerator, value)]} from llvm-dwarfdump text output."""
    text = _run([DWARFDUMP, "--debug-info", obj])
    entries = []
    cur = None
    for ln in text.splitlines():
        m = re.match(r"^(0x[0-9a-f]+):\s+(DW_TAG_\w+|NULL)", ln)
        if m:
            depth = len(re.match(r"^0x[0-9a-f]+:(\s*)", ln).group(1))
            cur = {"off": int(m.group(1), 16), "tag": m.group(2), "depth": depth, "attrs": {}}
            entries.append(cur)
            continue
        m = re.match(r"^\s+(DW_AT_\w+)\s+\((.*)\)\s*$", ln)
        if m and cur is not None:
            cur["attrs"][m.group(1)] = m.group(2)
    by_off = {e["off"]: i for i, e in enumerate(entries)}
    out = {}
    for e in entries:
        if e["tag"] != "DW_TAG_typedef" or "DW_AT_name" not in e["attrs"]:
            continue
        name = e["attrs"]["DW_AT_name"].strip('"')
        t = re.match(r"(0x[0-9a-f]+)", e["attrs"].get("DW_AT_type", ""))
        if not t:
            continue
        k = by_off.get(int(t.group(1), 16))
        if k is None or entries[k]["tag"] != "DW_TAG_enumeration_type":
            continue
        vals = []
        d = entries[k]["depth"]
        for c in entries[k + 1:]:
            if c["depth"] <= d:
                break
            if c["tag"] == "DW_TAG_enumerator":
                vals.append((c["attrs"]["DW_AT_name"].strip('"'),
                             int(c["attrs"]["DW_AT_const_value"], 0)))
        out[name] = vals
    return out


def load():
    """Return the upstream data dict (cached in build/conv/upstream.json)."""
    exe = build()
    cache = os.path.join(BUILD, "conv", "upstream.json")
    if not _stale(cache, [exe, os.path.abspath(__file__)]):
        with open(cache) as f:
            return json.load(f)
    data = json.loads(_run([exe]))
    enums = _dwarf_enums(os.path.join(OUT, "obj", "dump_info.o"))
    for tn, key in (("statenum_t", "state_names"), ("mobjtype_t", "mobj_names"),
                    ("spritenum_t", "sprite_enum"), ("sfxenum_t", "sfx_enum"),
                    ("weapontype_t", "weapon_names"), ("ammotype_t", "ammo_names")):
        if tn not in enums:
            raise ConvError("enum %s missing from the dumper debug info" % tn)
        vals = enums[tn]
        names = [None] * (max(v for _, v in vals) + 1)
        for n, v in vals:
            names[v] = n
        data[key] = names
    tmp = tmp_name(cache)
    with open(tmp, "w") as f:
        json.dump(data, f)
    os.replace(tmp, cache)
    return data
